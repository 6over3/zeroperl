sub TIEHASH { bless {}, $_[0] }
sub FETCH { $E{$_[1]} }
sub STORE { $E{$_[1]} = $_[2] }
sub DELETE { delete $E{$_[1]} }
sub EXISTS { exists $E{$_[1]} }
sub FIRSTKEY { my $a = scalar keys %E; each %E }
sub NEXTKEY { each %E }

tie our %!, __PACKAGE__;

sub import {
    my $pkg = shift;
    for my $sym (@_) {
        if ($sym eq ':POSIX') {
            require Exporter;
            Exporter::export_to_level($pkg, 1, undef, @EXPORT_OK);
        } elsif (exists $E{$sym}) {
            my $val = $E{$sym};
            no strict 'refs';
            *{caller()."::$sym"} = sub () { $val };
        }
    }
}

